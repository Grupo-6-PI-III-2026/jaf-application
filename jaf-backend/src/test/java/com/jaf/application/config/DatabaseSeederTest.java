package com.jaf.application.config;

import org.junit.jupiter.api.Test;
import org.springframework.boot.DefaultApplicationArguments;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.embedded.EmbeddedDatabaseBuilder;
import org.springframework.jdbc.datasource.embedded.EmbeddedDatabaseType;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertTrue;

class DatabaseSeederTest {
    @Test
    void reiniciarPreservaDadosEditadosESeedInsereSomenteAusentes() {
        var banco = new EmbeddedDatabaseBuilder()
                .generateUniqueName(true)
                .setType(EmbeddedDatabaseType.H2)
                .build();
        try {
            var jdbc = new JdbcTemplate(banco);
            jdbc.execute("""
                    CREATE TABLE funcionario (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        nome VARCHAR, email VARCHAR, senha VARCHAR, cargo_global VARCHAR, created_at DATE)
                    """);
            jdbc.execute("""
                    CREATE TABLE obra (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        titulo VARCHAR, orcamento VARCHAR, status VARCHAR, dt_inicio DATE, dt_termino_previsto DATE)
                    """);
            jdbc.execute("""
                    CREATE TABLE alocacao_obra (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        funcionario_id BIGINT, obra_id BIGINT, cargo VARCHAR, dt_inicio DATE)
                    """);
            jdbc.execute("""
                    CREATE TABLE gasto (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        descricao VARCHAR, categoria VARCHAR, metodo_pagamento VARCHAR, etapa VARCHAR,
                        valor DECIMAL(19,2), dt_gasto DATE, funcionario_id BIGINT, obra_id BIGINT,
                        reembolso_concluido BOOLEAN)
                    """);
            jdbc.execute("""
                    CREATE TABLE pagamento_reembolso (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        gasto_id BIGINT, valor DECIMAL(19,2), data_pagamento DATE, observacao VARCHAR)
                    """);
            var seeder = new DatabaseSeeder(jdbc);
            var args = new DefaultApplicationArguments(new String[0]);
            seeder.run(args);
            assertEquals(5, jdbc.queryForObject("SELECT COUNT(*) FROM obra", Integer.class));
            assertTrue(jdbc.queryForObject("SELECT COUNT(*) FROM pagamento_reembolso", Integer.class) > 0);

            jdbc.update("UPDATE obra SET orcamento = '987654', status = 'CONCLUIDA'");
            jdbc.update("UPDATE funcionario SET nome = 'Nome editado', cargo_global = 'ADMIN'");
            jdbc.update("UPDATE alocacao_obra SET cargo = 'ENGENHEIRO'");
            jdbc.update("UPDATE gasto SET etapa = 'Pintura', categoria = 'Cimento', valor = 9999.99");
            jdbc.update("UPDATE gasto SET reembolso_concluido = FALSE WHERE metodo_pagamento <> 'REEMBOLSO'");
            var obras = jdbc.queryForList("SELECT * FROM obra ORDER BY id");
            // Não incluir hashes de senha em possíveis mensagens de falha.
            var funcionarios = jdbc.queryForList("SELECT id, nome, email, cargo_global, created_at FROM funcionario ORDER BY id");
            var alocacoes = jdbc.queryForList("SELECT * FROM alocacao_obra ORDER BY id");
            var gastos = jdbc.queryForList("SELECT * FROM gasto ORDER BY id");
            var pagamentos = jdbc.queryForList("SELECT * FROM pagamento_reembolso ORDER BY id");

            seeder.run(args);
            seeder.run(args);

            assertEquals(obras, jdbc.queryForList("SELECT * FROM obra ORDER BY id"));
            assertEquals(funcionarios, jdbc.queryForList("SELECT id, nome, email, cargo_global, created_at FROM funcionario ORDER BY id"));
            assertEquals(alocacoes, jdbc.queryForList("SELECT * FROM alocacao_obra ORDER BY id"));
            assertEquals(gastos, jdbc.queryForList("SELECT * FROM gasto ORDER BY id"));
            assertEquals(pagamentos, jdbc.queryForList("SELECT * FROM pagamento_reembolso ORDER BY id"));
        } finally {
            banco.shutdown();
        }
    }
}